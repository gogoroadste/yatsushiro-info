// 別の語の一部に埋もれて誤爆する組み合わせだけを、名指しで打ち消す。
// 日本語は語の切れ目がないため、一般則で弾こうとすると
// 「停電情報」まで巻き添えになる。実データで見つけたものを個別に潰す方式にする。
const FALSE_HITS = [
  ["通電", "直通電話"],   // 「直通電話」の中の「通電」
  ["ガス", "ガスコンロ"], // 用途が違うもの（例示。増やせる）
];
function contains(text, kw){
  if (!text.includes(kw)) return false;
  for (const [k, ctx] of FALSE_HITS){
    if (k !== kw) continue;
    // 誤爆する文脈を取り除いてもまだ残るなら、本物の一致
    if (!text.split(ctx).join("").includes(kw)) return false;
  }
  return true;
}

export function classify(text){
  const s = String(text || "");
  let best = "sonota", bestScore = 0;
  for (const c of CATS){
    let score = 0;
    for (const k of c.kw){
      if (contains(s, k)) score += k.length >= 3 ? 2 : 1;
    }
    if (score > bestScore){ bestScore = score; best = c.id; }
  }
  return { cat: best, score: bestScore };
}

export function isUrgent(text){
  const s = String(text || "");
  return URGENT_KW.some(k => s.includes(k));
}
